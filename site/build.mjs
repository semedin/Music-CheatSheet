// Generates index.html (the home page) from site/catalog.mjs and writes the shared
// top bar into every root page and build template. Safe to run repeatedly.
//   node site/build.mjs
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {SECTIONS, DOCS, DOWNLOADS, NAV, TEMPLATES} from './catalog.mjs';

const here = path.dirname(fileURLToPath(import.meta.url)), root = path.dirname(here);
const exists = file => fs.existsSync(path.join(root, file));
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

export const START = '<!-- site-nav:start -->', END = '<!-- site-nav:end -->';

export function navBlock() {
  const items = NAV.filter(n => n.file === 'index.html' || exists(n.file)).map(n => {
    const files = [n.file, ...(n.match || [])].join(' ');
    return `<a href="${n.file}" data-files="${files}"${n.file === 'index.html' ? ' class="sn-brand"' : ''}>${n.file === 'index.html' ? 'FIELDWORK' : esc(n.label)}</a>`;
  }).join('');
  return `${START}<div id="site-nav" role="navigation" aria-label="All Fieldwork pages"><style>` +
    '#site-nav{all:initial;box-sizing:border-box;display:flex;align-items:center;gap:2px;width:100%;padding:6px 12px;overflow-x:auto;' +
    'background:#171e22;color:#c9cdc2;font:500 13px/1.3 system-ui,-apple-system,"Segoe UI",Arial,sans-serif;position:relative;z-index:1000;scrollbar-width:thin}' +
    '#site-nav a{all:unset;display:inline-block;padding:5px 9px;border-radius:4px;color:#c9cdc2;white-space:nowrap;cursor:pointer}' +
    '#site-nav a:hover{color:#fff;background:#283237}#site-nav a:focus-visible{outline:2px solid #ffc96e;outline-offset:1px}' +
    '#site-nav a[aria-current=page]{color:#171e22;background:#ffc96e}' +
    '#site-nav .sn-brand{font-weight:800;letter-spacing:.08em;color:#fff;margin-right:6px}' +
    '@media print{#site-nav{display:none}}' +
    `</style>${items}<script data-site-nav>(()=>{const f=decodeURIComponent(location.pathname.split('/').pop()||'index.html');` +
    `for(const a of document.querySelectorAll('#site-nav a'))if(a.dataset.files.split(' ').includes(f)){a.setAttribute('aria-current','page');break}})()</script></div>${END}`;
}

// Put the top bar into one HTML string: replace an existing bar, replace the
// retired V2 bar on V1 guides, or insert straight after <body>.
export function withNav(html, block = navBlock()) {
  const s = html.indexOf(START), e = html.indexOf(END);
  if (s !== -1 && e > s) return html.slice(0, s) + block + html.slice(e + END.length);
  const legacy = /\n?<div id="v2-navigation"[\s\S]*?<\/div>\n?/;
  if (legacy.test(html)) return html.replace(legacy, '\n' + block + '\n');
  const body = html.match(/<body[^>]*>/i);
  if (body) return html.replace(body[0], body[0] + '\n' + block);
  throw Error('No <body> tag or existing navigation to attach the top bar to');
}

function card(p) {
  const available = exists(p.file);
  const meta = [p.edition && `<span class="tag">${esc(p.edition)}</span>`, p.badge && `<span class="tag hot">${esc(p.badge)}</span>`].filter(Boolean).join('');
  const search = esc([p.title, p.edition, p.text, p.file].join(' ').toLowerCase());
  const docLink = p.doc && exists(p.doc) ? `<a class="more" href="${p.doc}">Notes: ${p.doc}</a>` : '';
  if (!available) return `<li class="card missing" data-search="${search}"><div class="head">${meta}</div><h3>${esc(p.title)}</h3><p>${esc(p.text)}</p><p class="file">${p.file} is not in this folder yet</p></li>`;
  return `<li class="card" data-search="${search}"><a class="open" href="${p.file}"><div class="head">${meta}</div><h3>${esc(p.title)}</h3><p>${esc(p.text)}</p><p class="file">${p.file}</p></a>${docLink}</li>`;
}

function size(file) {
  const b = fs.statSync(path.join(root, file)).size;
  return b > 1e6 ? (b / 1e6).toFixed(1) + ' MB' : Math.round(b / 1e3) + ' KB';
}

function hub() {
  const pageCount = SECTIONS.reduce((n, s) => n + s.pages.filter(p => exists(p.file)).length, 0);
  const sections = SECTIONS.map(s => `<section class="group" id="${s.id}" data-group><div class="group-head"><h2>${esc(s.title)}</h2><p>${esc(s.blurb)}</p></div><ul class="cards">${s.pages.map(card).join('')}</ul></section>`).join('\n');
  const docs = DOCS.filter(d => exists(d.file)).map(d => `<li><a href="${d.file}"><b>${esc(d.title)}</b><span>${esc(d.text)}</span><code>${d.file}</code></a></li>`).join('');
  const downloads = DOWNLOADS.filter(d => exists(d.file)).map(d => `<li><a href="${d.file}" download><b>${esc(d.title)}</b><span>${esc(d.text)}</span><code>${d.file} · ${size(d.file)}</code></a></li>`).join('');
  const chips = SECTIONS.map(s => `<a href="#${s.id}">${esc(s.title)}</a>`).join('');
  return `<!DOCTYPE html>
<!-- Generated by site/build.mjs from site/catalog.mjs. Edit those, not this file. -->
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="description" content="Fieldwork: offline electronic music studios, field guides, sound-design labs and MIDI packs for house, techno and trance.">
<title>Fieldwork — home</title>
<style>${fs.readFileSync(path.join(here, 'hub.css'), 'utf8')}</style></head>
<body>
${navBlock()}
<header class="hero"><div class="wrap">
<p class="eyebrow">Electronic music / Ableton Live / offline</p>
<h1>Everything in Fieldwork, in one place.</h1>
<p class="lede">${pageCount} standalone pages: studios that write MIDI, labs you can play, and field guides that measure what they argue. Every page works offline from this folder.</p>
<div class="start">
<a href="fieldwork-v3.html"><small>Write an idea</small><b>Motif Studio</b></a>
<a href="drum-library.html"><small>Program drums</small><b>The Kit</b></a>
<a href="serum-v2.html"><small>Design a sound</small><b>Sound Design V2</b></a>
</div></div></header>
<main class="wrap">
<div class="tools"><label class="search"><span>Find a page</span><input id="q" type="search" placeholder="Search: bass, chords, rumble, arrangement…" autocomplete="off"></label><nav class="jump" aria-label="Sections">${chips}<a href="#docs">Notes</a><a href="#downloads">MIDI packs</a></nav></div>
<p id="empty" class="empty" hidden>Nothing matches that search.</p>
${sections}
<section class="group" id="docs"><div class="group-head"><h2>Notes & documentation</h2><p>Written workflow, design decisions and validation for each release.</p></div><ul class="list">${docs}</ul></section>
<section class="group" id="downloads"><div class="group-head"><h2>MIDI packs</h2><p>Ready-made libraries to unzip straight into your Ableton User Library.</p></div><ul class="list">${downloads}</ul></section>
</main>
<footer class="wrap foot"><p>Keep every file in one folder: pages link to each other by file name. Press <kbd>/</kbd> to search.</p></footer>
<script>
const q=document.getElementById('q'),cards=[...document.querySelectorAll('.card')],groups=[...document.querySelectorAll('[data-group]')],empty=document.getElementById('empty');
function filter(){const terms=q.value.toLowerCase().trim().split(/\\s+/).filter(Boolean);let shown=0;
 for(const c of cards){const hit=terms.every(t=>c.dataset.search.includes(t));c.hidden=!hit;shown+=hit}
 for(const g of groups)g.hidden=![...g.querySelectorAll('.card')].some(c=>!c.hidden);empty.hidden=shown>0}
q.addEventListener('input',filter);
addEventListener('keydown',e=>{if(e.key==='/'&&document.activeElement!==q){e.preventDefault();q.focus()}else if(e.key==='Escape'&&document.activeElement===q){q.value='';filter()}});
</script>
</body></html>
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(path.join(root, 'index.html'), hub());
  const block = navBlock();
  const pages = fs.readdirSync(root).filter(f => f.endsWith('.html') && f !== 'index.html');
  for (const file of [...pages, ...TEMPLATES.filter(exists)]) {
    const full = path.join(root, file), html = fs.readFileSync(full, 'utf8'), next = withNav(html, block);
    if (next !== html) { fs.writeFileSync(full, next); console.log('top bar updated: ' + file); }
  }
  for (const n of NAV) if (!exists(n.file)) console.log(`note: ${n.file} is not in the folder, so it is left out of the top bar`);
  console.log('index.html written.');
}
